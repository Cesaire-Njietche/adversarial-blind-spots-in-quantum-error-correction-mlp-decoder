#!/usr/bin/env bash
#
# Generate d=5 depolarizing datasets, same style/convention as tuning_vic/d3/
# (see tuning_vic/d3/description.txt): one dataset per physical error rate p,
# rounds=9, depolarizing noise, written to tuning_vic/d5/<label>/dataset.npz
# (+ the .json sidecar written automatically by generate_datasets.py).
#
# Usage:
#   ./generate_d5_datasets.sh [SAMPLES] [OUTPUT_DIR]
#
#   SAMPLES     number of shots per dataset (default: 1000000, same as d3)
#   OUTPUT_DIR  where to write d5/<label>/dataset.npz (default: ./d5, next to this script)
#
# Run from anywhere -- paths are resolved relative to this script's location.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

DISTANCE=3
ROUNDS=9
SAMPLES="${1:-1000000}"
OUTPUT_DIR="${2:-"$SCRIPT_DIR/d3_1MIL"}"

# Same physical error rates already generated for d3.
NOISE_VALUES=(0.005)

mkdir -p "$OUTPUT_DIR"

for p in "${NOISE_VALUES[@]}"; do
    # Folder label: "0.014" -> "014" (drop the leading "0.")
    label="${p#0.}"
    dataset_dir="$OUTPUT_DIR/$label"
    mkdir -p "$dataset_dir"

    echo "########################################################"
    echo "Generating d${DISTANCE} depolarizing dataset: p=${p}, samples=${SAMPLES} -> ${dataset_dir}/dataset.npz"
    echo "########################################################"

    python3 "$SCRIPT_DIR/../data/generate_datasets.py" \
        --distance "$DISTANCE" \
        --rounds "$ROUNDS" \
        --samples "$SAMPLES" \
        --noise depolarizing \
        --noise-default "$p" \
        --output "$dataset_dir/dataset.npz" \
        --verbose
done

cat > "$OUTPUT_DIR/description.txt" <<EOF
${NOISE_VALUES[*]} each contain datasets with N=${SAMPLES} samples of :
{"distance": ${DISTANCE}, "rounds": ${ROUNDS}, "noise_type": "depolarizing", "noise_default": 0.x}

Generated by generate_d5_datasets.sh
EOF

echo "Done. Datasets written under: $OUTPUT_DIR"
